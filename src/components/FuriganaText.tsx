const SORTED_MIXED_TEMPLATES = [...MIXED_WORD_TEMPLATES].sort(
  (a, b) => b[0].length - a[0].length
);

const SORTED_KANJI_MAP = [...KANJI_READING_MAP].sort(
  (a, b) => b[0].length - a[0].length
);

const IS_PURE_KANJI = /^[\u4E00-\u9FAF\u3005]+$/;
const IS_KANA = /[\u3040-\u309F\u30A0-\u30FF]/;

export function stripFurigana(text: string): string {
  return text.replace(/\[([^\]]+)\]/g, '');
}

function splitOkurigana(
  surface: string,
  reading: string
): { prefix: string; stem: string; stemReading: string; suffix: string } {
  let suffixLen = 0;
  while (
    suffixLen < surface.length &&
    suffixLen < reading.length &&
    surface[surface.length - 1 - suffixLen] ===
      reading[reading.length - 1 - suffixLen] &&
    IS_KANA.test(surface[surface.length - 1 - suffixLen])
  ) {
    suffixLen++;
  }

  let prefixLen = 0;
  while (
    prefixLen < surface.length - suffixLen &&
    prefixLen < reading.length - suffixLen &&
    surface[prefixLen] === reading[prefixLen] &&
    IS_KANA.test(surface[prefixLen])
  ) {
    prefixLen++;
  }

  return {
    prefix: surface.slice(0, prefixLen),
    stem: surface.slice(prefixLen, surface.length - suffixLen),
    stemReading: reading.slice(prefixLen, reading.length - suffixLen),
    suffix: surface.slice(surface.length - suffixLen)
  };
}

function preprocessMixedWords(input: string): string {
  let result = input;
  for (const [plainWord, bracketedTemplate] of SORTED_MIXED_TEMPLATES) {
    if (result.includes(plainWord)) {
      // Replace only occurrences that aren't already followed by '['
      const escaped = plainWord.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const regex = new RegExp(`${escaped}(?!\\[)`, 'g');
      result = result.replace(regex, bracketedTemplate);
    }
  }
  return result;
}

function autoAnnotatePlainChunk(plain: string, keyPrefix: string): React.ReactNode[] {
  const nodes: React.ReactNode[] = [];
  let i = 0;
  let keyCounter = 0;

  while (i < plain.length) {
    // Only attempt dictionary match if current char or upcoming char involves Kanji
    let matched: [string, string] | null = null;
    for (const entry of SORTED_KANJI_MAP) {
      if (plain.startsWith(entry[0], i)) {
        matched = entry;
        break;
      }
    }

    if (matched) {
      const [surface, reading] = matched;
      const { prefix, stem, stemReading, suffix } = splitOkurigana(
        surface,
        reading
      );
      if (prefix) nodes.push(prefix);
      // Strictly guarantee that <ruby> ONLY wraps pure Kanji characters!
      if (stem && stemReading && IS_PURE_KANJI.test(stem)) {
        nodes.push(
          <ruby key={`${keyPrefix}-r-${keyCounter++}`} className="ruby-annotated">
            {stem}
            <rt className="text-[0.65em] text-[#0284C7] font-normal select-none leading-none">
              {stemReading}
            </rt>
          </ruby>
        );
      } else {
        nodes.push(stem);
      }
      if (suffix) nodes.push(suffix);
      i += surface.length;
    } else {
      nodes.push(plain[i]);
      i += 1;
    }
  }

  return nodes;
}

interface FuriganaTextProps {
  text: string;
  showFurigana?: boolean;
  className?: string;
}

export const FuriganaText: React.FC<FuriganaTextProps> = ({
  text,
  showFurigana = true,
  className = ''
}) => {
  if (!showFurigana) {
    return <span className={className}>{stripFurigana(text)}</span>;
  }

  const prepared = preprocessMixedWords(text);

  const parts: React.ReactNode[] = [];
  const regex = /([\u4E00-\u9FAF\u3005]+)\[([^\]]+)\]/g;
  let lastIdx = 0;
  let match: RegExpExecArray | null;
  let k = 0;

  while ((match = regex.exec(prepared)) !== null) {
    if (match.index > lastIdx) {
      parts.push(
        ...autoAnnotatePlainChunk(
          prepared.slice(lastIdx, match.index),
          `chunk-${k}`
        )
      );
    }
    const kanjiBase = match[1];
    const furiganaReading = match[2];
    // Guarantee only pure Kanji receives <ruby>
    if (IS_PURE_KANJI.test(kanjiBase)) {
      parts.push(
        <ruby key={`ex-${k++}`} className="ruby-annotated">
          {kanjiBase}
          <rt className="text-[0.65em] text-[#0284C7] font-normal select-none leading-none">
            {furiganaReading}
          </rt>
        </ruby>
      );
    } else {
      parts.push(kanjiBase);
    }
    lastIdx = regex.lastIndex;
  }

  if (lastIdx < prepared.length) {
    parts.push(
      ...autoAnnotatePlainChunk(prepared.slice(lastIdx), `tail-${k}`)
    );
  }

  return <span className={`leading-[2.1] ${className}`}>{parts}</span>;
};
